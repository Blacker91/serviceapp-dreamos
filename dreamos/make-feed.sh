#!/bin/bash
# Build the apt feed (branch "feed") from the released .deb files and push it.
# The branch has no history (force-pushed), only the current packages.
#
#   dreamos/make-feed.sh <dir with .deb files>        build + push
#   NOPUSH=1 dreamos/make-feed.sh <dir>               only build into $WORK/feed
#
# On the box (DreamOS 2.5, apt 1.0 with https):
#   echo "deb [trusted=yes] https://raw.githubusercontent.com/Blacker91/serviceapp-dreamos/feed ./" \
#     > /etc/apt/sources.list.d/serviceapp-dreamos.list
#   apt-get update && apt-get upgrade
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${WORK:-$ROOT/.work}"
SRC="${1:?usage: $0 <dir with .deb files>}"
F="$WORK/feed"
rm -rf "$F"; mkdir -p "$F"
cp "$SRC"/*.deb "$F/"
cd "$F"
dpkg-scanpackages -m . /dev/null 2>/dev/null | sed 's|^Filename: \./|Filename: |' > Packages
gzip -9n < Packages > Packages.gz
{
  echo "Origin: Blacker91"
  echo "Label: serviceapp-dreamos"
  echo "Suite: dreamos"
  echo "Date: $(LC_ALL=C date -u '+%a, %d %b %Y %H:%M:%S UTC')"
  echo "Architectures: mipsel armhf arm64"
  echo "Description: ServiceApp and exteplayer3 for DreamOS"
  for h in MD5Sum:md5sum SHA1:sha1sum SHA256:sha256sum; do
    echo "${h%%:*}:"
    for f in Packages Packages.gz; do
      printf ' %s %s %s\n' "$(${h##*:} "$f" | cut -d' ' -f1)" "$(stat -c %s "$f")" "$f"
    done
  done
} > Release
cat > README.md <<'EOF'
# apt feed for ServiceApp / exteplayer3 on DreamOS

Generated by `dreamos/make-feed.sh` (branch `dreamos`). Do not edit.

```sh
echo "deb [trusted=yes] https://raw.githubusercontent.com/Blacker91/serviceapp-dreamos/feed ./" > /etc/apt/sources.list.d/serviceapp-dreamos.list
apt-get update && apt-get upgrade
```
EOF
grep -E "^(Package|Version|Architecture):" Packages | paste - - -
[ -n "${NOPUSH:-}" ] && exit 0
git init -q -b feed
git add -A
git -c user.name="$(git -C "$ROOT" config user.name)" -c user.email="$(git -C "$ROOT" config user.email)" \
  commit -q -m "feed $(date -u +%F): $(ls *.deb | tr '\n' ' ')"
git push -q -f "$(git -C "$ROOT" remote get-url origin)" feed:feed
echo "pushed branch feed"
